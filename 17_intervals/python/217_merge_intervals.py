# LC#56 — Merge Intervals
# Difficulty: Medium
# Pattern: Sorting + Linear Scan
# Time: O(n log n) | Space: O(n)
#
# Approach:
#   Sort by start. Iterate: if current overlaps last merged interval,
#   extend its end. Otherwise append as new interval.

class Solution:
    def merge(self, intervals: list[list[int]]) -> list[list[int]]:
        intervals.sort(key=lambda x: x[0])
        merged = []
        for start, end in intervals:
            if merged and start <= merged[-1][1]:
                merged[-1][1] = max(merged[-1][1], end)
            else:
                merged.append([start, end])
        return merged


if __name__ == "__main__":
    s = Solution()
    assert s.merge([[1, 3], [2, 6], [8, 10], [15, 18]]) == [[1, 6], [8, 10], [15, 18]]
    assert s.merge([[1, 4], [4, 5]]) == [[1, 5]]
    assert s.merge([[1, 4], [0, 4]]) == [[0, 4]]
    print("All tests passed!")
